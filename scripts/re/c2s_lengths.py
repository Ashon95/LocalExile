"""Writes the Gateway's exact C->S length table from the extracted client writers.

`Agents/docs/protocol/c2s.json` is generated from Client/Game.exe by `scripts/re/ghidra/SendSites.java` and
`scripts/re/c2s_md.py`. Its `length` is set only when every writer of a message is exact (only fixed-size stream
writes: no branch, no loop, no call that takes the stream), so it is the client's own message size, not a guess.
`InstanceProtocol.SplitClientMessages` cannot frame an id it has no length for and drops the rest of the read after
it, so every exact id belongs in the table.

    python -I scripts/re/c2s_lengths.py          # write src/GameServer.Core/Protocol/Instance/ClientMessageLengths.cs
    python -I scripts/re/c2s_lengths.py --check  # exit 1 if the file on disk is out of date

Run from the repository root (Agents/docs/protocol/c2s.json is the input; Client/ is not needed).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "Agents", "docs", "protocol", "c2s.json")
OUT = os.path.join(ROOT, "src", "GameServer.Core", "Protocol", "Instance", "ClientMessageLengths.cs")
CRLF, LF = chr(13) + chr(10), chr(10)

# The client's plaintext opening: 0x0F ticket then 0x0E hello, 30 bytes together (InstanceProtocol.OpeningLength).
# TryReadOpening reads it before encryption starts, so it never reaches SplitClientMessages.
OPENING = {0x0E, 0x0F}


def lengths():
    """Every instance id whose writer is exact, id -> whole message length in bytes."""
    with open(SRC, encoding="utf-8") as f:
        messages = json.load(f)
    out = {}
    for m in messages:
        if m["protocol"] != "instance" or m["length"] is None:
            continue
        i = int(m["id"], 16)
        if i in OPENING:
            continue
        # 0x0085 is written inline (the id alone, no class: c2s_md.py); every other exact row has exactly one writer.
        inline = m.get("inline") and not m["classes"]
        assert len(m["classes"]) == 1 or inline, f"{i:#06x} has {len(m['classes'])} writers but an exact length"
        out[i] = m["length"]
    return dict(sorted(out.items()))


def render(table):
    lines = [
        "// Generated by `python -I scripts/re/c2s_lengths.py` from Agents/docs/protocol/c2s.json.",
        "// Do not edit by hand: regenerate it. The lengths are the client's own writers (c2s.md), not measurements.",
        "using System.Collections.Frozen;",
        "",
        "namespace GameServer.Core.Protocol.Instance;",
        "",
        "/// <summary>",
        f"/// Every C→S instance message whose writer is exact: {len(table)} ids, the whole message in bytes, id included.",
        "/// <see cref=\"InstanceProtocol.KnownClientLength\"/> keeps the named constants (which document the client addresses)",
        "/// and falls back to this table. Without a length",
        "/// <see cref=\"InstanceProtocol.SplitClientMessages\"/> cannot frame a message and drops the rest of the read it was in,",
        "/// so one missing id loses every message after it in that read.",
        "/// Regenerate with `python -I scripts/re/c2s_lengths.py`; `--check` reports a stale file.",
        "/// </summary>",
        "static class ClientMessageLengths",
        "{",
        "    internal static readonly FrozenDictionary<ushort, int> Exact = new Dictionary<ushort, int>",
        "    {",
    ]
    for i, n in table.items():
        lines.append(f"        [0x{i:04x}] = {n},")
    lines += [
        "    }.ToFrozenDictionary();",
        "}",
        "",
    ]
    return LF.join(lines)


def main():
    table = lengths()
    text = render(table)
    current = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8", newline="") as f:
            current = f.read()
        # A checkout may give it CRLF; the committed content is LF.
        current = current.replace(CRLF, LF)
    rel = os.path.relpath(OUT, ROOT)
    if "--check" in sys.argv[1:]:
        if current != text:
            print(f"{rel} is out of date: regenerate it with python -I scripts/re/c2s_lengths.py")
            return 1
        print(f"{rel} is up to date ({len(table)} ids)")
        return 0
    if current == text:
        print(f"{rel} unchanged ({len(table)} ids)")
        return 0
    with open(OUT, "w", encoding="utf-8", newline=LF) as f:
        f.write(text)
    print(f"wrote {rel}: {len(table)} exact ids")
    return 0


if __name__ == "__main__":
    sys.exit(main())
